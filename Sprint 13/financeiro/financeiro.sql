-- Soma do valor total faturado, desconsiderando faturas canceladas.
SELECT COALESCE(SUM(valor), 0) AS total_faturado
FROM faturas
WHERE status <> 'CANCELADA';

-- Bônus: debita somente se o saldo for suficiente.
-- Se não houver saldo ou o cliente não existir, a exceção interrompe
-- o bloco e a transação não persiste o débito nem a fatura.
BEGIN;

DO $$
DECLARE
    v_cliente_id BIGINT := 1;
    v_valor NUMERIC(12, 2) := 200.00;
    v_saldo_atual NUMERIC(12, 2);
BEGIN
    UPDATE clientes
       SET saldo = saldo - v_valor
     WHERE id = v_cliente_id
       AND saldo >= v_valor
    RETURNING saldo INTO v_saldo_atual;

    IF NOT FOUND THEN
        RAISE EXCEPTION
          'Saldo insuficiente ou cliente % inexistente. Débito cancelado.',
          v_cliente_id;
    END IF;

    INSERT INTO faturas (cliente_id, descricao, valor, status)
    VALUES (v_cliente_id, 'Débito de demonstração', v_valor, 'PAGA');

    RAISE NOTICE 'Débito realizado. Saldo restante: %', v_saldo_atual;
END
$$;

COMMIT;

SELECT id, nome, saldo FROM clientes ORDER BY id;
SELECT id, cliente_id, descricao, valor, status FROM faturas ORDER BY id;
